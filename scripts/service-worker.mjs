export function serviceWorkerSource({ version, assets }) {
  return `/* QuietChat static-only cache. Generated by scripts/build.mjs. */
'use strict';
const VERSION = ${JSON.stringify(version)};
const ASSETS = ${JSON.stringify(assets)};
const SCOPE = self.registration.scope;
const PREFIX = 'quietchat-static:' + SCOPE + ':';
const CACHE = PREFIX + VERSION;
const BY_URL = new Map(ASSETS.map(asset => [new URL(asset.path, SCOPE).href, asset]));
const HOME = new URL('index.html', SCOPE).href;
function hexlessBase64(bytes) {
  let text = '';
  for (const byte of bytes) text += String.fromCharCode(byte);
  return btoa(text);
}
async function valid(response, asset) {
  if (!response || !response.ok || response.type === 'opaque') return false;
  const digest = await crypto.subtle.digest('SHA-256', await response.clone().arrayBuffer());
  return hexlessBase64(new Uint8Array(digest)) === asset.hash;
}
async function verifiedCache() {
  if (!(await caches.has(CACHE))) return false;
  const cache = await caches.open(CACHE);
  for (const [url, asset] of BY_URL) if (!await valid(await cache.match(url), asset)) return false;
  return true;
}
self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    try {
      for (const [url, asset] of BY_URL) {
        const response = await fetch(new Request(url, { cache: 'reload', credentials: 'same-origin', integrity: 'sha256-' + asset.hash }));
        if (!await valid(response, asset)) throw new Error('Static asset integrity check failed');
        await cache.put(url, response);
      }
      if (!await verifiedCache()) throw new Error('Static cache incomplete');
    } catch (error) {
      await caches.delete(CACHE);
      throw error;
    }
    // Never skipWaiting: ALL tabs must close before an update can activate.
  })());
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    if (!await verifiedCache()) throw new Error('Static cache incomplete');
    for (const name of await caches.keys()) if (name.startsWith(PREFIX) && name !== CACHE) await caches.delete(name);
    // Deliberately no clients.claim(): never replace the code of an open session.
  })());
});
self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || url.search || url.hash) return;
  const key = url.href === SCOPE ? HOME : url.href;
  const asset = BY_URL.get(key);
  if (!asset) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const cached = await cache.match(key);
    if (await valid(cached, asset)) return cached;
    // Repair only the exact build artifact; never mix this session with newer code.
    try {
      const response = await fetch(new Request(key, { cache: 'reload', credentials: 'same-origin', integrity: 'sha256-' + asset.hash }));
      if (!await valid(response, asset)) throw new Error('Static asset mismatch');
      await cache.put(key, response.clone());
      return response;
    } catch {
      return new Response('QuietChat: offline cache unavailable. Lock and close every tab, then reopen online. If needed, clear this site cache after saving your encrypted key backup.', {
        status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8', 'Cache-Control': 'no-store' }
      });
    }
  })());
});
self.addEventListener('message', event => {
  const port = event.ports && event.ports[0];
  if (!port) return;
  if (event.data && event.data.type === 'VERIFY_CACHE') {
    event.waitUntil(verifiedCache().then(ready => port.postMessage({ ready, version: VERSION })).catch(() => port.postMessage({ ready: false, version: VERSION })));
  } else if (event.data && event.data.type === 'CLAIM_VERIFIED_BUILD' && event.data.version === VERSION && event.source && event.source.url && event.source.url.startsWith(SCOPE)) {
    // Only claim with an already active, fully cached matching build. The UI
    // blocks key creation/unlock until controlled. No update is activated here.
    event.waitUntil((async () => {
      const ready = await verifiedCache();
      if (ready) await self.clients.claim();
      port.postMessage({ ready, version: VERSION });
    })().catch(() => port.postMessage({ ready: false, version: VERSION })));
  } else if (event.data && event.data.type === 'ACTIVATE_UPDATE') {
    port.postMessage({ ready: false, requiresClose: true, version: VERSION });
  }
});
`;
}
